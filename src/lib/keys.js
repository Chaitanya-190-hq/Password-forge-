export function entropyBitsForBytes(bytes) {
  return bytes * 8;
}

export function validateByteLength(value, min = 8, max = 1024) {
  const length = Number(value);
  if (!Number.isInteger(length) || length < min || length > max) {
    throw new Error(`Length must be between ${min} and ${max} bytes.`);
  }
  return length;
}

import { bytesToHex, toBase64 } from './bytes.js';
import { getRandomBytes } from './random.js';

/**
 * Key Forge generators. Everything uses crypto.getRandomValues or
 * SubtleCrypto.generateKey — never a weak PRNG.
 */

export function randomHexString(byteLength) {
  return bytesToHex(getRandomBytes(byteLength));
}

export function randomBase64Token(byteLength) {
  return toBase64(getRandomBytes(byteLength));
}

export function randomUrlSafeToken(byteLength) {
  return toBase64(getRandomBytes(byteLength))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/g, '');
}

export function randomRawBytes(byteLength) {
  return getRandomBytes(byteLength);
}

/** Fresh AES-GCM key material, exported as raw bytes for offline use. */
export async function generateAesKeyMaterial(bits = 256) {
  const allowed = [128, 192, 256];
  if (!allowed.includes(bits)) throw new Error('AES key length must be 128, 192 or 256 bits.');
  const key = await crypto.subtle.generateKey({ name: 'AES-GCM', length: bits }, true, [
    'encrypt',
    'decrypt',
  ]);
  const raw = new Uint8Array(await crypto.subtle.exportKey('raw', key));
  return {
    type: `AES-${bits}-GCM`,
    bytes: raw,
    base64: toBase64(raw),
    hex: bytesToHex(raw),
    bits,
  };
}

/**
 * ECDSA P-256 signing key pair. Public material is safe to share; private
 * material must only be exported after an explicit warning in the UI.
 */
export async function generateSigningKeyPair() {
  const pair = await crypto.subtle.generateKey(
    { name: 'ECDSA', namedCurve: 'P-256' },
    true,
    ['sign', 'verify'],
  );
  const [publicJwk, privateJwk] = await Promise.all([
    crypto.subtle.exportKey('jwk', pair.publicKey),
    crypto.subtle.exportKey('jwk', pair.privateKey),
  ]);
  return {
    type: 'ECDSA P-256',
    publicJwk,
    privateJwk,
    publicPem: jwkToPem(publicJwk),
  };
}

function base64UrlToBase64(value) {
  return value.replace(/-/g, '+').replace(/_/g, '/');
}

/** Minimal SPKI PEM encoding of a P-256 public JWK (for pasting into configs). */
function jwkToPem(jwk) {
  const prefix = 'MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAE';
  const point = `${base64UrlToBase64(jwk.x)}${base64UrlToBase64(jwk.y)}`;
  const body = `${prefix}${point}`.replace(/(.{64})/g, '$1\n').trim();
  return `-----BEGIN PUBLIC KEY-----\n${body}\n-----END PUBLIC KEY-----`;
}

